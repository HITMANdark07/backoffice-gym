import { TASKS } from '@backoffice-gym/core';

export interface SuiteModel {
  id: string;
  /** OpenRouter provider pin; omit for mock models. */
  provider?: string;
}

/** Free OpenRouter models that completed a full mcp-evals run before (2026-10-21). */
export const FREE_MODELS: SuiteModel[] = [
  { id: 'minimax/minimax-m3.1-flash:free', provider: 'minimax' },
  { id: 'nvidia/nemotron-3-ultra-550b-a55b:free', provider: 'nvidia' },
];

export const taskId = (slug: string, seed: number): string => `${slug}--s${seed}`;

/** JSON strings are valid YAML double-quoted scalars, so this quotes anything safely. */
const q = (s: string): string => JSON.stringify(s);

export interface BuildSuiteOptions {
  models: SuiteModel[];
  seeds: number[];
  slugs?: string[];
  name?: string;
  /** Path of the bin from the suite file's directory. */
  serverPath?: string;
  /** Test hook: replace every prompt. */
  promptOverride?: string;
}

/** An mcp-evals suite: one task per template × seed, scored by the hidden __score tool. */
export function buildSuiteYaml(o: BuildSuiteOptions): string {
  const tasks = TASKS.filter((t) => !o.slugs || o.slugs.includes(t.slug));
  const serverPath = o.serverPath ?? '{suite_dir}/../packages/mcp/bin/backoffice-gym-mcp.mjs';
  const lines = [
    '# Generated by packages/mcp/scripts/write-suite.ts. Do not edit by hand.',
    `suite: ${o.name ?? 'backoffice-gym'}`,
    'version: 1',
    'servers:',
    '  backoffice-gym:',
    '    command: node',
    `    args: [${[serverPath, '--task', '{task}', '--seed', '{seed}'].map(q).join(', ')}]`,
    '    hidden_tools: [__score]',
    'models:',
    ...o.models.map((m) => (m.provider ? `  - { id: ${q(m.id)}, provider: ${q(m.provider)} }` : `  - ${q(m.id)}`)),
    'defaults: { repeats: 1, max_steps: 40, timeout_s: 300, temperature: 0 }',
    'tasks:',
  ];
  for (const t of tasks) {
    for (const seed of o.seeds) {
      lines.push(
        `  - id: ${taskId(t.slug, seed)}`,
        `    prompt: ${q(o.promptOverride ?? t.generate(seed).prompt)}`,
        `    vars: { task: ${q(t.slug)}, seed: ${q(String(seed))} }`,
        '    graders: [{ type: env_reward, tool: __score, min: 1 }]',
      );
    }
  }
  return `${lines.join('\n')}\n`;
}
